const dictionaries: Record<Lang, Record<string, string>> = { en, hi };

export const LANGUAGES: { code: Lang; label: string; native: string; flag: string }[] = [
  { code: 'en', label: 'English', native: 'English', flag: '🇬🇧' },
  { code: 'hi', label: 'Hindi', native: 'हिन्दी', flag: '🇮🇳' },
];

interface I18nValue {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: (key: string, fallback?: string) => string;
  isHindi: boolean;
}

const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useLocalStorage<Lang>('drillmind.lang', 'en');

  const t = useCallback(
    (key: string, fallback?: string) => {
      return dictionaries[lang]?.[key] ?? en[key] ?? fallback ?? key;
    },
    [lang],
  );

  const value = useMemo<I18nValue>(
    () => ({ lang, setLang, t, isHindi: lang === 'hi' }),
    [lang, setLang, t],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  const value = useContext(I18nContext);
  if (!value) throw new Error('useI18n must be used inside <I18nProvider>');
  return value;
}

/** Two-way label helper for fields the API already localises. */
export function bilingual(isHindi: boolean, english: string, hindi: string): string {
  return isHindi ? hindi : english;
}
